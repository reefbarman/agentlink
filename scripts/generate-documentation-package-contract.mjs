import { readFile, writeFile } from "node:fs/promises";

import { fileURLToPath } from "node:url";
import { format } from "oxfmt";
import path from "node:path";
import process from "node:process";

const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const packagePath = path.join(repoRoot, "package.json");
const changelogPath = path.join(repoRoot, "CHANGELOG.md");
const formatterConfigPath = path.join(repoRoot, ".oxfmtrc.json");
const referencesPath = path.join(
  repoRoot,
  "resources",
  "builtin-skills",
  "documentation",
  "references",
);
const generatedFiles = [
  {
    outputPath: path.join(referencesPath, "package-contract.md"),
    content: await formatMarkdown(
      renderPackageContract(JSON.parse(await readFile(packagePath, "utf8"))),
    ),
  },
  {
    outputPath: path.join(referencesPath, "release-notes.md"),
    content: await readFile(changelogPath, "utf8"),
  },
];
const check = process.argv.includes("--check");

for (const { outputPath, content } of generatedFiles) {
  if (check) {
    let existing = "";
    try {
      existing = await readFile(outputPath, "utf8");
    } catch {
      // Report missing generated files through the same drift error.
    }
    if (existing !== content) {
      throw new Error(
        "Bundled generated documentation is out of date. Run `npm run docs:generate` and commit resources/builtin-skills/documentation/references/package-contract.md and release-notes.md.",
      );
    }
  } else {
    await writeFile(outputPath, content, "utf8");
  }
}

async function formatMarkdown(content) {
  const config = JSON.parse(await readFile(formatterConfigPath, "utf8"));
  const { code, errors } = await format("package-contract.md", content, config);
  if (errors.length > 0) {
    throw new Error(
      `Unable to format bundled package documentation: ${errors.map((error) => error.message).join("; ")}`,
    );
  }
  return code;
}

function renderPackageContract(manifest) {
  const lines = [
    "<!-- Generated by scripts/generate-documentation-package-contract.mjs. Do not edit manually. -->",
    "",
    "# AgentLink Package Contract",
    "",
    "This bundled reference is generated from the extension's `package.json` during builds. It contains the exact extension metadata, commands, views, and settings that the documentation skill may quote. For behavior and workflows, read the owning topic reference.",
    "",
    "## Extension metadata",
    "",
    ...renderTable(
      ["Field", "Value"],
      [
        ["Name", `\`${escapeInline(manifest.displayName ?? manifest.name)}\``],
        ["Version", `\`${escapeInline(manifest.version)}\``],
        ["Publisher", `\`${escapeInline(manifest.publisher)}\``],
        ["License", `\`${escapeInline(manifest.license)}\``],
        ["VS Code engine", `\`${escapeInline(manifest.engines?.vscode)}\``],
        ["Node.js engine", `\`${escapeInline(manifest.engines?.node)}\``],
      ],
    ),
    "",
    "## Commands",
    "",
    ...renderTable(
      ["Command", "Title"],
      sortedBy(
        manifest.contributes?.commands ?? [],
        (command) => command.command,
      ).map(({ command, title }) => [
        `\`${escapeInline(command)}\``,
        escapeTable(title),
      ]),
    ),
    "",
    "## Views",
    "",
    ...renderTable(
      ["Container", "View ID", "Name"],
      renderViews(manifest.contributes?.views ?? {}),
    ),
    "",
    "## Settings",
    "",
    ...renderTable(
      ["Setting", "Scope", "Default", "Allowed values", "Description"],
      renderSettings(manifest.contributes?.configuration?.properties ?? {}),
    ),
    "",
  ];

  return `${lines.join("\n")}\n`;
}

function renderViews(views) {
  return Object.entries(views)
    .flatMap(([container, entries]) =>
      (entries ?? []).map(({ id, name }) => [
        `\`${escapeInline(container)}\``,
        `\`${escapeInline(id)}\``,
        escapeTable(name),
      ]),
    )
    .sort(([left], [right]) => left.localeCompare(right));
}

function renderSettings(properties) {
  return Object.entries(properties)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([setting, definition]) => [
      `\`${escapeInline(setting)}\``,
      escapeInline(definition.scope ?? "window"),
      renderDefault(definition.default),
      escapeTable(renderAllowedValues(definition)),
      escapeTable(definition.description ?? ""),
    ]);
}

function renderTable(headers, rows) {
  const widths = headers.map((header, column) =>
    Math.max(header.length, ...rows.map((row) => row[column].length)),
  );
  const renderRow = (row) =>
    `| ${row.map((cell, column) => cell.padEnd(widths[column])).join(" | ")} |`;

  return [
    renderRow(headers),
    `| ${widths.map((width) => "-".repeat(width)).join(" | ")} |`,
    ...rows.map(renderRow),
  ];
}

function renderAllowedValues(definition) {
  if (Array.isArray(definition.enum)) {
    return definition.enum
      .map((value) => `\`${escapeInline(value)}\``)
      .join(", ");
  }
  if (definition.pattern)
    return `Pattern: \`${escapeInline(definition.pattern)}\``;
  if (definition.type) return `Type: \`${escapeInline(definition.type)}\``;
  return "—";
}

function renderDefault(value) {
  if (value === undefined) return "—";
  return `\`${escapeInline(JSON.stringify(value))}\``;
}

function escapeInline(value) {
  return String(value ?? "").replaceAll("`", "\\`");
}

function escapeTable(value) {
  return String(value ?? "")
    .replaceAll("|", "\\|")
    .replaceAll("\n", " ");
}

function sortedBy(items, selector) {
  return [...items].sort((left, right) =>
    String(selector(left)).localeCompare(String(selector(right))),
  );
}
